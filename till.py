# Οι πωλήσεις της βάρδιας, όπως τις πέρασε το ταμείο.
sales = [0.60, 1.80, 2.80, 3.20, 4.20, 5.20]

# Ένα τοστ επιστράφηκε, οπότε η πώληση ακυρώθηκε.
refunds = [2.80]

# Όσα μετρητά μέτρησε ο ταμίας στο συρτάρι, στο κλείσιμο.
counted = 15.00

sum = sum(sales)
print("Πωλήσεις:", sum)

net = sum - sum(refunds)
print("Καθαρό σύνολο:", net)
print("Συμφωνεί με το ταμείο:", net == counted)
