# Τα αιτήματα επιστροφής της ημέρας.
# Κάθε γραμμή: κωδικός;ημέρες από την παραλαβή;κατάσταση;κατηγορία;απόδειξη
REQUESTS = [
    "ΕΠΣ-101;5;ΣΦΡΑΓΙΣΜΕΝΟ;ΗΛΕΚΤΡΟΝΙΚΑ;ΑΠΔ-77120",
    "ΕΠΣ-102;14;ΣΦΡΑΓΙΣΜΕΝΟ;ΠΑΙΧΝΙΔΙΑ;ΑΠΔ-77455",
    "ΕΠΣ-103;3;ΑΝΟΙΓΜΕΝΟ;ΗΛΕΚΤΡΟΝΙΚΑ;ΑΠΔ-77890",
    "ΕΠΣ-104;21;ΑΝΟΙΓΜΕΝΟ;ΕΠΟΧΙΑΚΑ;ΑΠΔ-78002",
    "ΕΠΣ-105;2;ΣΦΡΑΓΙΣΜΕΝΟ;ΕΣΩΡΟΥΧΑ;ΑΠΔ-78110",
    "ΕΠΣ-106;6;ΣΦΡΑΓΙΣΜΕΝΟ;ΗΛΕΚΤΡΟΝΙΚΑ;",
]

for request in REQUESTS:
    code, days_text, condition, category, receipt = request.split(";")
    if receipt.strip():
        if category != "ΕΣΩΡΟΥΧΑ":
            days = int(days_text)
            if days < 14:
                if condition == "ΣΦΡΑΓΙΣΜΕΝΟ":
                    print(f"{code}: δεκτή")
                else:
                    print(f"{code}: απορρίπτεται - ανοιγμένη συσκευασία")
            else:
                print(f"{code}: απορρίπτεται - πέρασαν {days} ημέρες")
        else:
            print(f"{code}: απορρίπτεται - η κατηγορία δεν επιστρέφεται")
    else:
        print(f"{code}: απορρίπτεται - χωρίς απόδειξη")
